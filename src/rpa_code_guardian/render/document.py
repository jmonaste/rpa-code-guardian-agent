def render_compliance(state: dict | object) -> str:
    get = state.get if isinstance(state, dict) else lambda k, d=None: getattr(state, k, d)
    inv: ProjectInventory = get("inventory")
    requirements = get("requirements", []) or []
    compliance: dict = get("compliance", {}) or {}

    title = inv.meta.name or Path(inv.root).name or "UiPath Process"
    out: list[str] = [f"# {title} — PDD Compliance Report", ""]
    out.append(
        f"Generated by rpa-code-guardian v{__version__} on {date.today().isoformat()}."
    )
    out.append("")
    out.append("## Scope and method")
    out.append("")
    out.append(
        f"{len(requirements)} requirements were extracted from the Process Definition "
        "Document and assessed against the implemented project "
        f"({len(inv.workflows)} workflows). Each requirement was verified against the "
        "static analysis of the source workflows and the project configuration; "
        "verdicts cite the implementing workflows as evidence. Runtime behavior was "
        "not executed as part of this assessment."
    )

    counts: dict[str, int] = {}
    for item in compliance.values():
        counts[item.verdict] = counts.get(item.verdict, 0) + 1
    out += ["", "## Verdict summary", "", "| Verdict | Count |", "|---------|-------|"]
    for verdict in ("Compliant", "Partially compliant", "Non-compliant", "Not verifiable"):
        if counts.get(verdict):
            out.append(f"| {verdict} | {counts[verdict]} |")

    out += [
        "", "## Requirements traceability matrix", "",
        "| ID | Requirement | Verdict | Evidence |",
        "|----|-------------|---------|----------|",
    ]
    for req in requirements:
        item = compliance.get(req.id)
        verdict = item.verdict if item else "Not assessed"
        evidence = ", ".join(item.evidence) if item and item.evidence else "-"
        out.append(f"| {req.id} | {md_cell(req.text)} | {verdict} | {md_cell(evidence)} |")

    deviations = [
        (req, compliance[req.id]) for req in requirements
        if req.id in compliance and compliance[req.id].verdict != "Compliant"
    ]
    out += ["", "## Gaps and deviations", ""]
    if not deviations:
        out.append("No gaps or deviations were identified.")
    for req, item in deviations:
        out += [f"### {req.id} — {item.verdict}", "", f"Requirement: {req.text}", ""]
        out.append(item.justification)
        if item.gap:
            out += ["", f"Gap: {item.gap}"]
        out.append("")

    total = len(requirements)
    ok = counts.get("Compliant", 0)
    out += ["", "## Conclusion", ""]
    if total == 0:
        out.append("No verifiable requirements could be extracted from the provided PDD.")
    else:
        out.append(
            f"{ok} of {total} extracted requirements are fully compliant"
            f" ({counts.get('Partially compliant', 0)} partially compliant,"
            f" {counts.get('Non-compliant', 0)} non-compliant,"
            f" {counts.get('Not verifiable', 0)} not verifiable)."
            " Items listed under Gaps and deviations should be reviewed with the"
            " process owner before sign-off."
        )
    return lint_markdown("\n".join(out))
